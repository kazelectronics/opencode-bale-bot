const DICTIONARIES: Record<Locale, Record<MessageKey, string>> = { en, fa };

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "en" || value === "fa";
}

export function normalizeLocale(value: string | null | undefined, fallback: Locale = "en"): Locale {
  return isLocale(value) ? value : fallback;
}

export type MessageParams = Record<string, string | number>;

export function t(locale: Locale, key: MessageKey, params: MessageParams = {}): string {
  const dictionary = DICTIONARIES[locale] ?? DICTIONARIES.en;
  const template = dictionary[key] ?? en[key] ?? key;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (whole, name: string) => {
    const value = params[name];
    return value === undefined ? whole : String(value);
  });
}

/** Convenience for modules that store a locale alongside the chat. */
export function translator(locale: Locale): (key: MessageKey, params?: MessageParams) => string {
  return (key, params) => t(locale, key, params);
}